def multi_table_full_discovery(scored: list[dict]) -> tuple[int, int]:
    """(N, M): of the M multi-table questions, how many have every search
    approach discover their full must-have set in *every* run (before rerank).

    Data-derived so the reported count can't go stale as questions are added.
    """
    by_q: dict[str, list[dict]] = {}
    for s in scored:
        if s["category"].startswith("multi") and s["approach"] in SEARCH_APPROACHES:
            by_q.setdefault(s["question_id"], []).append(s)
    full = sum(1 for runs in by_q.values() if all(s["discovery_recall"] >= 1.0 for s in runs))
    return full, len(by_q)


def methodology_footer(
    metadata: dict,
    n_cells: int,
    n_errors: int,
    empties: dict[str, int] | None = None,
    multi_full: tuple[int, int] | None = None,
) -> str:
    lines = ["## Methodology & reproducibility", ""]
    lines.append(
        f"- **Design:** factorial — approach × tier × question × run. "
        f"{n_cells} approach-runs scored" + (f" ({n_errors} errored)." if n_errors else ".")
    )
    if empties:
        detail = ", ".join(f"{APPROACH_LABELS.get(a, a)} {n}" for a, n in sorted(empties.items()))
        lines.append(
            f"- **Empty returns (counted, not dropped):** {sum(empties.values())} "
            f"non-error runs returned zero ranked tables ({detail}) — search found "
            "nothing in scope for that question. These are scored as recall 0, so "
            "they pull the means down honestly rather than being excluded."
        )
    lines.append(
        f"- **Enrichment tiers:** identical {metadata.get('corpus_size', '?')}-table "
        f"corpus replicated ×{len(metadata.get('tiers', []))}, differing only in "
        f"catalog enrichment ({metadata.get('distractor_count', '?')} distractor tables)."
    )
    lines.append(
        f"- **Replicates:** n={metadata.get('runs_per_cell', '?')} runs per cell; "
        "metrics reported as medians with IQR bands."
    )
    lines.append(
        f"- **Models:** agent `{metadata.get('agent_model', '?')}`, reranker "
        f"`{metadata.get('tool_model', '?')}` at temperature "
        f"{metadata.get('reranker_temperature', '?')}, top_k={metadata.get('top_k', '?')}."
    )
    pkgs = metadata.get("packages", {})
    if pkgs:
        pkg_str = ", ".join(f"{k} {v}" for k, v in pkgs.items())
        lines.append(f"- **Packages:** {pkg_str}.")
    lines.append(
        "- **Isolation:** each approach runs in its own `InMemoryRunner`, one at a "
        "time, so latency and token counts carry no parallel-contention artifact."
    )
    multi_frac = f"{multi_full[0]} of {multi_full[1]}" if multi_full else "most"
    lines.append(
        "- **Scope-query probe (reproducible):** `examples/probe_scope_filter.py` "
        "replays the exact `search_entries` call the search approaches make "
        "(`semantic_search=True`, scoped by `parent:datasets/…`) and documents the "
        "correct query syntax. It shows: the `parent:` predicate **is honored** "
        "with a free-text question; an earlier low-recall result was a "
        "client-side query-construction bug (**wrapping the question in "
        "parentheses silently voided the predicate** — an isolation table pins "
        "this as the sole trigger, with `AND` connectors and parent-value "
        f"parentheses both harmless); with the corrected bare query, {multi_frac} "
        "multi-table questions retrieve *all* their must-have tables before any "
        "rerank; the `scope=` request field is project/org-level only (a "
        "dataset-level ref → 400), so dataset scoping must go through `parent:`; "
        "and the returned count is governed by search's internal relevance cutoff, "
        "not `page_size` (raising it 20 → 100 adds nothing; no threshold parameter "
        "or relevance score is exposed). The harness also records per-run "
        "`search_stats` (`raw_search_count`, `out_of_scope_dropped`) for every "
        "search-based cell — now expected to show zero out-of-scope drops."
    )
    lines.append("")
    return "\n".join(lines)


def readme_digest(scored: list[dict], approaches: list[str]) -> str:
    """Compact results digest injected into readme.md between the RESULTS markers.

    One finding sentence + the headline recall table + a pointer into the deep
    report. The README summarizes; `examples/results.md` carries the detail.
    """
    lines = [
        "_Auto-generated by `examples/build_results.py` — do not edit between the markers._",
        "",
        "**Scoped semantic search retrieves the right tables; the reranker adds "
        "precision, not recall.** With the corrected scoped query (a bare "
        "`parent:datasets/…` predicate), search returns a small, already-ranked, "
        "in-scope set holding every must-have table for nearly all multi-table "
        "questions **before any rerank**. `Search Direct` (search order, no rerank) "
        "vs `KC Search` (rerank on the identical retrieval) measures the reranker's "
        "marginal value directly. This matters at scale: past a few dozen tables "
        "the whole-corpus shortcut closes and search recall becomes the pipeline's "
        "hard ceiling — the reranker can raise precision, never recall.",
        "",
        "| Approach | Discovery recall | Final recall | Rerank loss |",
        "|---|---|---|---|",
    ]
    for a in approaches:
        disc = _mean([s["discovery_recall"] for s in scored if s["approach"] == a])
        final = _mean([s["final_recall"] for s in scored if s["approach"] == a])
        role = " (control)" if a in CONTROL_APPROACHES else ""
        lines.append(
            f"| {APPROACH_LABELS[a]}{role} | {_fmt_num(disc, 3)} | "
            f"{_fmt_num(final, 3)} | {_fmt_num(disc - final, 3)} |"
        )
    lines += [
        "",
        "Means across all questions × tiers × runs (medians saturate at 100% on "
        "this corpus). Full tables, plots, per-category breakdown, cost/latency, "
        "and the one residual relevance gap: "
        "[`examples/results.md`](examples/results.md).",
    ]
    return "\n".join(lines)


def corpus_table() -> str:
    """The 15-table corpus rendered from setup.py's CORPUS (single source of truth).

    Injected into readme.md between the CORPUS markers so the table can never
    drift from what ``scripts/setup.py`` actually creates. Answer tables first,
    then distractors, so the three baited traps stand out.
    """
    n_distractor = sum(1 for t in CORPUS if t.get("role") == "distractor")
    n_answer = len(CORPUS) - n_distractor
    lines = [
        "_Auto-generated by `examples/build_results.py` from `scripts/setup.py`'s "
        "`CORPUS` — do not edit between the markers._",
        "",
        f"The identical corpus — **{n_answer} answer tables + {n_distractor} "
        f"distractors = {len(CORPUS)}** — is replicated into every tier dataset. "
        "Distractors look relevant by name but are never a correct answer.",
        "",
        "| Table | Role | Source (`bigquery-public-data.…`) | What it holds |",
        "|---|---|---|---|",
    ]
    ordered = sorted(CORPUS, key=lambda t: t.get("role") == "distractor")
    for t in ordered:
        role = "distractor" if t.get("role") == "distractor" else "answer"
        source = t["source"].replace("bigquery-public-data.", "")
        desc = " ".join(t["description"].split())
        lines.append(f"| `{t['name']}` | {role} | `{source}` | {desc} |")
    return "\n".join(lines)


def questions_table(questions: list[dict]) -> str:
    """All questions rendered from questions.json, grouped by category.

    Shows each question's `must_have` tables (the recall target) and any baited
    `distractor`, so a reader sees the full graded set and what each trap tests
    without opening the JSON.
    """
    counts: dict[str, int] = {}
    for q in questions:
        counts[q["category"]] = counts.get(q["category"], 0) + 1
    comp = ", ".join(
        f"{counts[c]} {c}" for c in CATEGORY_ORDER if c in counts
    )
    lines = [
        "_Auto-generated by `examples/build_results.py` from "
        "`examples/questions.json` — do not edit between the markers._",
        "",
        f"All **{len(questions)}** graded questions ({comp}). `Must-have` tables "
        "are the recall target; `distractor` is the baited wrong table (blank if "
        "none). Full grading rubric: "
        "[`examples/GROUND_TRUTH.md`](examples/GROUND_TRUTH.md).",
        "",
        "| # | Category | Question | Must-have tables | Distractor baited |",
        "|---|---|---|---|---|",
    ]
    order = {c: i for i, c in enumerate(CATEGORY_ORDER)}
    ordered = sorted(questions, key=lambda q: (order.get(q["category"], 99), q["id"]))
    for q in ordered:
        rel = q.get("relevance", {})
        must = ", ".join(f"`{t}`" for t in rel.get("must_have", [])) or "—"
        distract = ", ".join(f"`{t}`" for t in rel.get("distractor", [])) or "—"
        question = q["question"].replace("|", "\\|")
        lines.append(
            f"| `{q['id']}` | {q['category']} | {question} | {must} | {distract} |"
        )
    return "\n".join(lines)


def _inject_between(text: str, start: str, end: str, body: str) -> str | None:
    """Return ``text`` with the region between ``start``/``end`` replaced by ``body``.

    Returns None if either marker is absent (the section is skipped rather than
    guessed at a location — the README owns where each generated block lives) or
    if the replacement would be a no-op.
    """
    if start not in text or end not in text:
        return None
    pre, rest = text.split(start, 1)
    _, post = rest.split(end, 1)
    new = f"{pre}{start}\n\n{body}\n\n{end}{post}"
    return new if new != text else None


def inject_readme_sections(sections: list[tuple[str, str, str]]) -> list[str]:
    """Inject each ``(start, end, body)`` marker block into readme.md in one pass.

    Returns the list of marker-start strings that were actually written (so the
    caller can report which sections updated). Missing markers are silently
    skipped — the README owns whether a section exists.
    """
    if not README_FILE.exists():
        return []
    text = README_FILE.read_text()
    written: list[str] = []
    for start, end, body in sections:
        new = _inject_between(text, start, end, body)
        if new is not None:
            text = new
            written.append(start)
    if written:
        README_FILE.write_text(text)
    return written


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=str, default=str(RESULTS_FILE))
    parser.add_argument("--output", type=str, default=str(OUTPUT_MD))
    parser.add_argument("--no-plots", action="store_true", help="Skip PNG plots")
    args = parser.parse_args()

    results_path = Path(args.results)
    if not results_path.exists():
        raise SystemExit(f"No results at {results_path}. Run run_questions.py first.")

    with open(results_path) as f:
        doc = json.load(f)
    metadata = doc.get("metadata", {})
    cells = doc.get("cells", [])

    scored = []
    n_errors = 0
    empties: dict[str, int] = {}
    for cell in cells:
        s = score_cell(cell)
        if s is None:
            n_errors += 1
            continue
        if not cell.get("ranked_tables"):
            empties[cell["approach"]] = empties.get(cell["approach"], 0) + 1
        s.update(
            {
                "question_id": cell["question_id"],
                "approach": cell["approach"],
                "tier": cell["tier"],
                "category": cell["category"],
            }
        )
        scored.append(s)

    if not scored:
        raise SystemExit("No scorable cells found.")

    approaches = [a for a in APPROACH_LABELS if any(s["approach"] == a for s in scored)]
    tiers = sorted({s["tier"] for s in scored})
    categories = [c for c in CATEGORY_ORDER if any(s["category"] == c for s in scored)]

    plots: dict[str, str] = {}
    if not args.no_plots:
        plots = render_plots(scored, approaches, tiers, categories)

    def _img(name: str) -> str:
        """Markdown image for a rendered plot, or '' if plots were skipped."""
        return f"![{name}]({plots[name]})\n" if name in plots else ""

    parts = [
        "# NL2SQL retrieval benchmark — results",
        "",
        "Six table-discovery approaches for BigQuery NL2SQL, scored on a "
        "factorial experiment that isolates **catalog enrichment** as the "
        "independent variable. See [`readme.md`](../readme.md) for the challenge "
        "and approach spec cards, and [`GROUND_TRUTH.md`](GROUND_TRUTH.md) for the "
        "grading rubric.",
        "",
        # Lead with the finding: where does recall actually leak?
        discovery_vs_rerank(scored, approaches),
        _img("discovery_vs_final"),
        discovery_miss_by_category(scored, approaches, categories),
        worked_example(cells),
        # Then the saturated overall + enrichment-response tables.
        headline_table(scored, approaches),
        tier_response_table(scored, approaches, tiers),
        _img("recall_vs_tier"),
        category_table(scored, approaches, categories),
        _img("ndcg_by_category"),
        cost_latency_table(scored, approaches),
        _img("latency_cost"),
        methodology_footer(
            metadata, len(scored), n_errors, empties, multi_table_full_discovery(scored)
        ),
    ]
    report = "\n".join(parts)

    Path(args.output).write_text(report)
    print(f"Wrote {args.output}")
    if plots:
        print(f"Wrote {len(plots)} plot(s) to {PLOTS_DIR}")

    with open(QUESTIONS_FILE) as f:
        questions = json.load(f)
    written = inject_readme_sections(
        [
            (README_START, README_END, readme_digest(scored, approaches)),
            (CORPUS_START, CORPUS_END, corpus_table()),
            (QUESTIONS_START, QUESTIONS_END, questions_table(questions)),
        ]
    )
    if written:
        print(f"Injected {len(written)} generated section(s) into {README_FILE}")


if __name__ == "__main__":
    main()
