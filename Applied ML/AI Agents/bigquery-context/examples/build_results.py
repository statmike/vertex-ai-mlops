def render_plots(
    scored: list[dict], approaches: list[str], tiers: list[int], categories: list[str]
) -> dict[str, str]:
    """Render PNG plots; return {name: path} (paths relative to examples/)."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    PLOTS_DIR.mkdir(parents=True, exist_ok=True)
    written: dict[str, str] = {}

    # 1. Recall-vs-tier curves (the payoff visual).
    fig, ax = plt.subplots(figsize=(7, 4.5))
    for a in approaches:
        ys, los, his = [], [], []
        for t in tiers:
            vals = [s["final_recall"] for s in scored if s["approach"] == a and s["tier"] == t]
            ys.append(_median(vals))
            lo, hi = _iqr(vals)
            los.append(lo)
            his.append(hi)
        style = "-o" if a in CONTEXT_APPROACHES else "--s"
        ax.plot(tiers, ys, style, label=APPROACH_LABELS[a], linewidth=2, markersize=6)
        ax.fill_between(tiers, los, his, alpha=0.12)
    ax.set_xticks(tiers)
    ax.set_xticklabels([TIER_LABELS[t] for t in tiers], rotation=15, ha="right")
    ax.set_ylabel("Final recall (median, IQR band)")
    ax.set_title(
        "Retrieval recall vs enrichment tier\n(solid = context approaches, dashed = controls)"
    )
    ax.set_ylim(0, 1.05)
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=8, loc="lower right")
    fig.tight_layout()
    p = PLOTS_DIR / "recall_vs_tier.png"
    fig.savefig(p, dpi=120)
    plt.close(fig)
    written["recall_vs_tier"] = str(p.relative_to(Path(__file__).parent))

    # 2. Latency & cost bars (highest tier).
    max_tier = max(tiers)
