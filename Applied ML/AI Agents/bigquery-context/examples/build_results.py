# Report sections
# ---------------------------------------------------------------------------
def _fmt_pct(v: float) -> str:
    return "—" if math.isnan(v) else f"{v:.0%}"


def _fmt_num(v: float, digits: int = 2) -> str:
    return "—" if math.isnan(v) else f"{v:.{digits}f}"


def discovery_vs_rerank(scored: list[dict], approaches: list[str]) -> str:
    """Lead finding: decompose recall into discovery (did the candidate set even
    contain the table?) vs rerank loss (did the reranker drop it from top-k?).

    Uses **means**, not medians: on an easy corpus most cells score 1.0, so the
    median saturates at 100% and hides the tail. The mean exposes where recall
    actually leaks — and separating discovery from final recall shows *which
    stage* leaks it. This is the headline: the reranker rarely drops a table the
    discovery step surfaced, so search-based approaches are capped by discovery
    recall (semantic search missing join-partner tables), not by reranking.
    """
    lines = ["## Headline — where recall actually leaks", ""]
    lines += [
        "Recall decomposed into two stages: **discovery recall** (was the "
        "must-have table in the candidate set at all?) and **final recall** "
        "(did it survive the reranker's top-5 cut?). The gap between them is "
        "**rerank loss**. Means, not medians — the corpus is easy enough that "
        "medians saturate at 100% and hide the tail.",
        "",
        "| Approach | Discovery recall | Final recall | Rerank loss |",
        "|---|---|---|---|",
    ]
    for a in approaches:
        disc = _mean([s["discovery_recall"] for s in scored if s["approach"] == a])
        final = _mean([s["final_recall"] for s in scored if s["approach"] == a])
        loss = disc - final
        role = " (control)" if a in CONTROL_APPROACHES else ""
        lines.append(
            f"| {APPROACH_LABELS[a]}{role} | {_fmt_num(disc, 3)} | "
            f"{_fmt_num(final, 3)} | {_fmt_num(loss, 3)} |"
        )
    lines.append("")
    lines.append(
        "_**Search's ceiling is a discovery problem, not a reranking one.** The "
        "search-based approaches (`KC Search`, `Semantic`) show ~zero rerank "
        "loss — the reranker keeps every must-have table the search surfaced — "
        "yet their discovery recall caps well below 1.0. The missing tables were "
        "never in the candidate set, and a direct probe of `search_entries` "
        "(see Methodology) shows the candidate set leaks for **two distinct "
        "reasons**:_"
    )
    lines.append("")
    lines += [
        "1. **Relevance gap (disparate joins).** The API returns *well under* the "
        "`page_size=20` budget — a handful of tables, all in scope — and the "
        "join-partner table simply never ranks, because it shares no salient term "
        "with the question. The page budget is not the constraint here; semantic "
        "relevance is.",
        "2. **Scope leak (related joins).** The `parent:(datasets/…)` predicate "
        "**is enforceable — but it is relaxed when combined with a free-text "
        "question under semantic search.** The predicate *alone* returns only "
        "in-scope tables (a clean control: 15 raw, 15 in-scope, 0 pollution), so "
        "the catalog can honor it. But the moment the natural-language question is "
        "ANDed with it, the API fills the *entire* page of 20 with tables from "
        "unrelated datasets, and the in-scope join partner is crowded out; our "
        "client-side scope filter then strips the out-of-scope tables, leaving a "
        "tiny candidate set still missing the partner. No query reformulation "
        "fixes this — exact `parent=`, the `fully_qualified_name` prefix, and "
        "explicit `NOT` negation all leak identically — and a wider page only "
        "admits more pollution (in-scope count stays pinned as `page_size` grows "
        "20 → 100). The probe script reproduces all of this (see Methodology).",
        "",
        "_In both cases the must-have table is absent **before** reranking, so the "
        "reranker cannot recover it. The cache-based approaches see the whole "
        "scoped corpus (discovery recall 1.0), so their only loss is at the "
        "reranker._",
    ]
    lines.append("")
    return "\n".join(lines)


def discovery_miss_by_category(scored: list[dict], approaches: list[str],
                               categories: list[str]) -> str:
    """Discovery recall by approach × category — isolates *which questions* the
    search-based approaches fail to surface all tables for (the join questions).
    """
    lines = ["### Discovery recall by question category", ""]
    header = "| Category | " + " | ".join(APPROACH_LABELS[a] for a in approaches) + " |"
    sep = "|---|" + "|".join("---" for _ in approaches) + "|"
    lines += [header, sep]
    for cat in categories:
        row = [cat]
        for a in approaches:
            vals = [s["discovery_recall"] for s in scored
                    if s["approach"] == a and s["category"] == cat]
            row.append(_fmt_num(_mean(vals), 2))
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")
    lines.append(
        "_Where the candidate set is complete (1.00) vs missing a must-have "
        "table. The search-based approaches drop on both join categories, but for "
        "different reasons (see the worked examples): `multi-table-disparate` "
        "misses are the **relevance gap**, while the sharper `multi-table-related` "
        "drop is driven by the **scope leak** — out-of-scope tables consuming the "
        "page budget._"
    )
    lines.append("")
    return "\n".join(lines)


def _pick_worked_example(cells: list[dict], category: str | None = None,
                         exclude_qids: set[str] | None = None) -> dict | None:
    """Find the sharpest single question to illustrate the discovery gap.

    Criteria, computed from raw cells (so the example can't drift from the data):
    a multi-table question where a search approach misses a ``must_have`` table
    in *every* run, while a full-corpus approach surfaces it. Returns a dict with
    the question, the missed table, the tables search kept, the min in-scope
    ``nominated_count`` search reached across runs, and the contrast — or None if
    no such clean case exists.

    ``category`` restricts to one question category (e.g. isolate the
    disparate-join regime from the related-join regime); ``exclude_qids`` skips
    questions already used as an example.
    """
    exclude_qids = exclude_qids or set()
    by_q_appr: dict[tuple, list[dict]] = {}
    q_meta: dict[str, dict] = {}
    for c in cells:
        if "error" in c:
            continue
        qid = c["question_id"]
        q_meta.setdefault(qid, {
            "question": c.get("question", ""),
            "category": c.get("category", ""),
            "must_have": c.get("relevance", {}).get("must_have", []),
        })
        by_q_appr.setdefault((qid, c["approach"]), []).append(c)

    best = None
    for qid, meta in q_meta.items():
        must = set(meta["must_have"])
        if qid in exclude_qids:
            continue
        if len(must) < 2 or not meta["category"].startswith("multi"):
            continue
        if category is not None and meta["category"] != category:
            continue
        # Which must_have tables does a search approach miss in ALL runs?
        for search_appr in SEARCH_APPROACHES:
            runs = by_q_appr.get((qid, search_appr), [])
            if not runs:
                continue
            missed_every_run = set(must)
            kept_union: set[str] = set()
            min_nominated = None
            for c in runs:
                nom = {_short(t) for t in c.get("nominated", [])}
                missed_every_run &= (must - nom)
                kept_union |= (must & nom)
                nc = c.get("nominated_count", len(c.get("nominated", [])))
                min_nominated = nc if min_nominated is None else min(min_nominated, nc)
            if not missed_every_run:
                continue
            # Confirm a full-corpus approach surfaces the missed table(s).
            # Prefer KC Context (a *catalog* full-corpus approach) as the
            # contrast over raw BQ enumeration — it's the more on-point rebuttal.
            surfacer = None
            for full_appr in ("kc_context", "context_prefilter", "bq_tools"):
                if full_appr not in FULL_CORPUS_APPROACHES:
                    continue
                fruns = by_q_appr.get((qid, full_appr), [])
                if fruns and missed_every_run <= {
                    _short(t) for t in fruns[0].get("nominated", [])
                }:
                    surfacer = full_appr
                    break
            if surfacer is None:
                continue
            cand = {
                "qid": qid,
                "question": meta["question"],
                "category": meta["category"],
                "must_have": sorted(must),
                "missed": sorted(missed_every_run),
                "kept": sorted(kept_union),
                "min_nominated": min_nominated if min_nominated is not None else 0,
                "search_appr": search_appr,
                "surfacer": surfacer,
                "n_runs": len(runs),
            }
            # Prefer the example that misses the most tables, then most runs.
            if best is None or (
                len(cand["missed"]), cand["n_runs"]
            ) > (len(best["missed"]), best["n_runs"]):
                best = cand
    return best


def _worked_example_row(ex: dict) -> list[str]:
    """The needed/surfaced/missed contrast table for one worked example."""
    missed = ", ".join(f"`{t}`" for t in ex["missed"])
    kept = ", ".join(f"`{t}`" for t in ex["kept"]) or "—"
    search_label = APPROACH_LABELS[ex["search_appr"]]
    surf_label = APPROACH_LABELS[ex["surfacer"]]
    return [
        f"**Question ({ex['category']}):** \"{ex['question']}\"",
        "",
        "| | Tables |",
        "|---|---|",
        f"| **Needed (`must_have`)** | {', '.join(f'`{t}`' for t in ex['must_have'])} |",
        f"| **{search_label} surfaced (in scope)** | {kept} |",
        f"| **{search_label} missed (every one of {ex['n_runs']} runs)** | {missed} |",
        f"| **{surf_label} surfaced** | all of the above |",
        "",
    ]


def worked_example(cells: list[dict]) -> str:
    """Two data-derived questions, one per discovery-failure mechanism.

    The first is a *disparate*-join question (relevance gap: search returns fewer
    than the page budget, all in scope, and still misses the partner). The second
    is a *related*-join question (scope leak: search fills the page with
    out-of-scope tables, collapsing the in-scope candidate set). Falls back to a
    single example if only one regime has a clean case.
    """
    disparate = _pick_worked_example(cells, category="multi-table-disparate")
    related = _pick_worked_example(
        cells, category="multi-table-related",
        exclude_qids={disparate["qid"]} if disparate else None,
    )
    if disparate is None and related is None:
        return ""

    lines = ["### Worked examples — join partners search never surfaces", ""]

    if disparate is not None:
        lines.append("**Mechanism 1 — relevance gap.**")
        lines.append("")
        lines += _worked_example_row(disparate)
        missed = ", ".join(f"`{t}`" for t in disparate["missed"])
        surf_label = APPROACH_LABELS[disparate["surfacer"]]
        lines += [
            f"_Semantic search ranks the tables whose text matches the question, "
            f"but {missed} is required only by the *logic* of the question — it "
            f"shares no salient term with the query. Search returned only "
            f"{disparate['min_nominated']} in-scope tables (page budget to spare), "
            f"so the budget is not the constraint; relevance is. The full-corpus "
            f"approach ({surf_label}) sees every scoped table, carries {missed} "
            f"into reranking, and answers correctly._",
            "",
        ]

    if related is not None:
        lines.append("**Mechanism 2 — scope leak (`parent:` not enforced).**")
        lines.append("")
        lines += _worked_example_row(related)
        missed = ", ".join(f"`{t}`" for t in related["missed"])
        surf_label = APPROACH_LABELS[related["surfacer"]]
        lines += [
            f"_Here the failure is not relevance but scope. A direct probe of "
            f"`search_entries` for this question (see Methodology) returns a full "
            f"page of 20, but most are tables from **unrelated datasets** that the "
            f"`parent:(datasets/…)` predicate did not exclude; the client-side "
            f"scope filter drops them, collapsing the in-scope candidate set to as "
            f"few as {related['min_nominated']} and leaving {missed} out. The "
            f"predicate is not inherently broken — issued *alone* it returns only "
            f"in-scope tables — but it is relaxed once the free-text question is "
            f"ANDed in under semantic search, and no reformulation or wider page "
            f"recovers the missing partner. The full-corpus approach "
            f"({surf_label}) is immune because it never depends on the page "
            f"budget._",
            "",
        ]

    return "\n".join(lines)


def discussion_at_scale(scored: list[dict], approaches: list[str]) -> str:
    """Interpretation: what the discovery gap implies as the corpus grows."""
    lines = ["## Discussion — what this implies at scale", ""]
    lines += [
        "On this 15-table corpus the discovery gap looks survivable: you can feed "
        "the *entire* scoped corpus to the reranker (as `KC Context` does) and let "
        "it sort out relevance, so search's missing tables never bind. That is "
        "exactly why enrichment tier does not move final recall here — recall is "
        "**discovery-bound**, and the full-corpus approaches route around search "
        "entirely. But that escape hatch closes as the corpus grows, and two "
        "things follow.",
        "",
        "**1. At scale, search becomes mandatory — and its recall becomes the "
        "pipeline's ceiling.** A reranker cannot ingest thousands of candidate "
        "tables: context limits, token cost, and the accuracy decay of "
        "long-candidate reranking all bite. So beyond a few dozen tables you "
        "*must* use `search_entries` to subset before reranking. At that point the "
        "reranker can only improve **precision** within what search returned — it "
        "can never recover a `must_have` table search left out. Search recall "
        "therefore sets a hard ceiling the reranker is powerless to raise, and "
        "this benchmark measures that ceiling at ~0.88 (0.56 on related-join "
        "questions). A gap you route around at 15 tables is the binding constraint "
        "at 10,000.",
        "",
        "**2. The two failure mechanisms need different fixes — and one is a "
        "precondition for the other.**",
        "",
        "- **Enforce the `parent:` scope predicate under semantic search (fixes "
        "the scope leak).** The predicate is enforceable — issued alone it returns "
        "only in-scope tables — but it is relaxed the moment a free-text question "
        "is combined with it under `semantic_search=True`, so a scoped search "
        "still returns tables from unrelated datasets that pollute the whole page "
        "and crowd the in-scope partner out. This is a **precondition** for any "
        "page-budget-based fix — while the combined-query predicate is relaxed, a "
        "*wider* page simply admits more pollution, not more in-scope tables "
        "(measured: in-scope count stays flat as `page_size` grows 20 → 100). "
        "Making the predicate bind in the combined semantic case is the cheapest, "
        "highest-leverage change and is squarely within the catalog's control.",
        "- **A retrieval front-end that decomposes the question and fans out "
        "(fixes the relevance gap).** Plan the query into sub-needs (e.g. "
        "\"weather stations\", \"county boundaries\", \"population per area\") and "
        "issue a *targeted* similarity search per sub-need, then union the "
        "results. This attacks the disparate-join failure mode: the join-partner "
        "table has no lexical anchor to the raw question, but it does match a "
        "decomposed sub-need. It scales *up* — it both subsets aggressively "
        "**and** keeps recall high enough to feed the reranker. (Simply raising "
        "`page_size` scales *down*, not up, and only helps once scope is "
        "enforced.)",
        "",
        "**A catalog-native opportunity.** The failing tables are join partners, "
        "and Knowledge Catalog already models joins: `lookup_context` exposes a "
        "`frequent_joins` field. If `search_entries` expanded its results along "
        "known join edges — surface table A, pull in A's frequent-join partners — "
        "it would close the exact gap this benchmark isolates, using signal the "
        "catalog is positioned to already have. (In this corpus the tables are "
        "freshly created views, so auto-generated join hints are not yet "
        "populated; the mechanism, not this run's data, is the point.)",
        "",
    ]
    return "\n".join(lines)


def headline_table(scored: list[dict], approaches: list[str]) -> str:
    """Overall median metrics per approach (across all questions × tiers × runs)."""
    lines = ["## Summary metrics — all questions, all tiers", ""]
    header = "| Metric | " + " | ".join(APPROACH_LABELS[a] for a in approaches) + " |"
    sep = "|---|" + "|".join("---" for _ in approaches) + "|"
    lines += [header, sep]

    metrics = [
        ("Final recall", "final_recall", _fmt_pct),
        ("Discovery recall", "discovery_recall", _fmt_pct),
        ("Recall@5", "recall_at_k", _fmt_pct),
        ("Precision", "precision", _fmt_pct),
        ("MRR", "mrr", lambda v: _fmt_num(v, 2)),
        ("nDCG@5", "ndcg", lambda v: _fmt_num(v, 2)),
        ("Latency p50 (s)", "latency_s", lambda v: _fmt_num(v, 2)),
        ("Reranker tokens", "reranker_total_tokens", lambda v: _fmt_num(v, 0)),
    ]
    for label, metric, fmt in metrics:
        row = [label]
        for a in approaches:
            vals = [s[metric] for s in scored if s["approach"] == a]
            row.append(fmt(_median(vals)))
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")
    lines.append(
        "_Values are **medians** across all approach-runs — they saturate at 100% "
        "on this easy corpus, which is why the headline above uses means to expose "
        "the tail. Recall counts `must_have` tables; precision credits "
        "`must_have`+`nice_to_have` and is diluted by ranked distractors. See "
        "`GROUND_TRUTH.md`._"
    )
    lines.append("")
    return "\n".join(lines)


def tier_response_table(scored: list[dict], approaches: list[str], tiers: list[int]) -> str:
    """Final-recall median by approach × tier — the enrichment-response headline."""
    lines = ["## Enrichment response — final recall by tier", ""]
    header = "| Approach | " + " | ".join(TIER_LABELS[t] for t in tiers) + " | Δ (t3−t0) |"
    sep = "|---|" + "|".join("---" for _ in tiers) + "|---|"
    lines += [header, sep]

    for a in approaches:
        cells = []
        per_tier_median = {}
        for t in tiers:
            vals = [s["final_recall"] for s in scored
                    if s["approach"] == a and s["tier"] == t]
            m = _median(vals)
            per_tier_median[t] = m
            cells.append(_fmt_pct(m))
        lo, hi = min(tiers), max(tiers)
        delta = per_tier_median.get(hi, float("nan")) - per_tier_median.get(lo, float("nan"))
        tag = " 🟢" if (a in CONTEXT_APPROACHES and not math.isnan(delta) and delta > 0.05) else ""
        delta_str = "—" if math.isnan(delta) else f"{delta:+.0%}{tag}"
        role = "control" if a in CONTROL_APPROACHES else "context"
        lines.append(f"| {APPROACH_LABELS[a]} ({role}) | " + " | ".join(cells) + f" | {delta_str} |")

    lines.append("")
    lines.append(
        "_The tier axis: controls (`BQ Tools`, `KC Search`) read little/no tier "
        "enrichment; context approaches read progressively more. On this corpus "
        "final recall is flat across tiers — enrichment does not move top-5 recall "
        "here because recall is bounded by **discovery**, not by the metadata the "
        "reranker sees (see the headline above). 🟢 would mark a context approach "
        "gaining >5pp from tier 0 → tier 3._"
    )
    lines.append("")
    return "\n".join(lines)


