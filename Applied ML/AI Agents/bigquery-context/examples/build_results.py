# nDCG graded gains by relevance class.
GAIN = {"must_have": 2.0, "nice_to_have": 1.0, "distractor": 0.0}

RERANK_K = 5  # Recall@k / precision cutoff


# ---------------------------------------------------------------------------
# Per-cell scoring
# ---------------------------------------------------------------------------
def _short(full_id: str) -> str:
    return full_id.rsplit(".", 1)[-1]


def _relevance_sets(relevance: dict) -> tuple[set, set, set]:
    must = set(relevance.get("must_have", []))
    nice = set(relevance.get("nice_to_have", []))
    dist = set(relevance.get("distractor", []))
    return must, nice, dist


def _dcg(gains: list[float]) -> float:
    return sum(g / math.log2(i + 2) for i, g in enumerate(gains))


def score_cell(cell: dict) -> dict | None:
    """Compute graded retrieval metrics for one approach-run cell.

    Returns None for error cells (no ranked/nominated output).
    """
    if "error" in cell:
        return None

    must, nice, _dist = _relevance_sets(cell.get("relevance", {}))
    ranked = [_short(t["table_id"]) for t in cell.get("ranked_tables", [])]
    nominated = [_short(t) for t in cell.get("nominated", [])]
    ranked_set = set(ranked)
    nominated_set = set(nominated)

    # Recall: fraction of must_have tables retrieved.
    final_recall = len(ranked_set & must) / len(must) if must else 1.0
    discovery_recall = len(nominated_set & must) / len(must) if must else 1.0

    # Precision: relevant (must ∪ nice) fraction of ranked; distractors dilute.
    relevant = must | nice
    precision = (len(ranked_set & relevant) / len(ranked_set)) if ranked_set else 0.0

    # nDCG with graded gains (must=2, nice=1, distractor/other=0).
    def gain_for(name: str) -> float:
        if name in must:
            return GAIN["must_have"]
        if name in nice:
            return GAIN["nice_to_have"]
        return 0.0

    gains = [gain_for(n) for n in ranked[:RERANK_K]]
    ideal_gains = sorted(
        [GAIN["must_have"]] * len(must) + [GAIN["nice_to_have"]] * len(nice),
        reverse=True,
    )[:RERANK_K]
    idcg = _dcg(ideal_gains)
    ndcg = (_dcg(gains) / idcg) if idcg else 1.0

    return {
        "final_recall": final_recall,
        "discovery_recall": discovery_recall,
        "precision": precision,
        "ndcg": ndcg,
        "latency_s": cell.get("latency_s", 0.0),
        "reranker_total_tokens": cell.get("reranker_total_tokens", 0),
        "reranker_calls": cell.get("reranker_calls", 0),
    }


# ---------------------------------------------------------------------------
# Aggregation helpers
# ---------------------------------------------------------------------------
def _median(vals: list[float]) -> float:
    return float(np.median(vals)) if vals else float("nan")


def _mean(vals: list[float]) -> float:
    return float(np.mean(vals)) if vals else float("nan")


def _iqr(vals: list[float]) -> tuple[float, float]:
    if not vals:
        return (float("nan"), float("nan"))
    return (float(np.percentile(vals, 25)), float(np.percentile(vals, 75)))


def _pctl(vals: list[float], p: float) -> float:
    return float(np.percentile(vals, p)) if vals else float("nan")


# ---------------------------------------------------------------------------
# Report sections
# ---------------------------------------------------------------------------
def _fmt_pct(v: float) -> str:
    return "—" if math.isnan(v) else f"{v:.0%}"


def _fmt_num(v: float, digits: int = 2) -> str:
    return "—" if math.isnan(v) else f"{v:.{digits}f}"


def discovery_vs_rerank(scored: list[dict], approaches: list[str]) -> str:
    """Lead finding: decompose recall into discovery (did the candidate set even
    contain the table?) vs rerank loss (did the reranker drop it from top-k?).

    Uses **means**, not medians: on an easy corpus most cells score 1.0, so the
    median saturates at 100% and hides the tail. The mean exposes where recall
    actually leaks — and separating discovery from final recall shows *which
    stage* leaks it. This is the headline: with the corrected scoped query,
    semantic search retrieves the must-have tables for nearly every question, so
    the reranker's job is precision, not recall recovery; the residual miss is a
    single relevance-gap join, not a reranking failure.
    """
    lines = ["## Headline — discovery vs reranking", ""]
    lines += [
        "Recall decomposed into two stages: **discovery recall** (was the "
        "must-have table in the candidate set at all?) and **final recall** "
        "(did it survive the reranker's top-5 cut?). The gap between them is "
        "**rerank loss**. Means, not medians — the corpus is easy enough that "
        "medians saturate at 100% and hide the tail.",
        "",
        "| Approach | Discovery recall | Final recall | Rerank loss |",
        "|---|---|---|---|",
    ]
    for a in approaches:
        disc = _mean([s["discovery_recall"] for s in scored if s["approach"] == a])
        final = _mean([s["final_recall"] for s in scored if s["approach"] == a])
        loss = disc - final
        role = " (control)" if a in CONTROL_APPROACHES else ""
        lines.append(
            f"| {APPROACH_LABELS[a]}{role} | {_fmt_num(disc, 3)} | "
            f"{_fmt_num(final, 3)} | {_fmt_num(loss, 3)} |"
        )
    lines.append("")
    mf_n, mf_m = multi_table_full_discovery(scored)
    lines.append(
        "_**Scoped semantic search retrieves the right tables — the reranker's job "
        "is precision, not recall recovery.** Once the search is scoped with the "
        "correct query syntax (a bare `parent:datasets/…` predicate; see "
        "Methodology), it returns a small, already-ranked, in-scope set that "
        f"contains all must-have tables for {mf_n} of the {mf_m} multi-table "
        "questions — including the disparate joins — **before any reranking**. "
        "`Search Direct` "
        "takes that set as its answer with no LLM at all; `KC Search` and "
        "`Semantic` add a rerank on top of the identical retrieval, and the "
        "`Search Direct`-vs-`KC Search` gap measures exactly what that rerank buys. "
        "The search-based approaches show ~zero rerank loss: the reranker keeps the "
        "must-have tables search surfaced. The full-corpus approaches (`BQ Tools`, "
        "`KC Context`, `Pre-Filter`) see the whole scoped corpus, so their "
        "discovery recall is 1.0 by construction and any loss is purely at the "
        "reranker._"
    )
    lines.append("")
    lines += [
        "The **one** residual retrieval gap is a genuine relevance miss, not a "
        "scope or budget problem:",
        "",
        "- **Relevance gap (one disparate join).** It takes **two factors "
        "together**: the required table is keyed to a *different geography* than "
        "the question names (a county question needing a ZIP-keyed population "
        "table) **and** the join is implied only by a computed ratio, sharing no "
        "salient term with the query — so it never ranks into the returned set. "
        "Matching the geography *or* naming the partner restores discovery to "
        "100%, so neither factor alone is sufficient. The API returns *well "
        "under* the `page_size` budget (a handful of in-scope tables, all "
        "correctly scoped), so the budget is not the constraint; semantic "
        "relevance is. Raising `page_size` does not surface it (the count is "
        "governed by search's internal relevance cutoff, not the page size). The "
        "catalog-native fix is join-aware expansion (`frequent_joins`), not a "
        "wider page — see the worked example.",
        "",
        "_This is the only case where a must-have table is absent **before** "
        "reranking, so it is the only recall the reranker cannot recover. Every "
        "other multi-table question — related and disparate alike — retrieves its "
        "full must-have set from the scoped search directly._",
    ]
    lines.append("")
    return "\n".join(lines)


