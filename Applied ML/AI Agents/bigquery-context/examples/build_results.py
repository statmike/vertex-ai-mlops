def methodology_footer(metadata: dict, n_cells: int, n_errors: int,
                       empties: dict[str, int] | None = None) -> str:
    lines = ["## Methodology & reproducibility", ""]
    lines.append(
        f"- **Design:** factorial — approach × tier × question × run. "
        f"{n_cells} approach-runs scored"
        + (f" ({n_errors} errored)." if n_errors else ".")
    )
    if empties:
        detail = ", ".join(
            f"{APPROACH_LABELS.get(a, a)} {n}" for a, n in sorted(empties.items())
        )
        lines.append(
            f"- **Empty returns (counted, not dropped):** {sum(empties.values())} "
            f"non-error runs returned zero ranked tables ({detail}) — search found "
            "nothing in scope for that question. These are scored as recall 0, so "
            "they pull the means down honestly rather than being excluded."
        )
    lines.append(
        f"- **Enrichment tiers:** identical {metadata.get('corpus_size', '?')}-table "
        f"corpus replicated ×{len(metadata.get('tiers', []))}, differing only in "
        f"catalog enrichment ({metadata.get('distractor_count', '?')} distractor tables)."
    )
    lines.append(
        f"- **Replicates:** n={metadata.get('runs_per_cell', '?')} runs per cell; "
        "metrics reported as medians with IQR bands."
    )
    lines.append(
        f"- **Models:** agent `{metadata.get('agent_model', '?')}`, reranker "
        f"`{metadata.get('tool_model', '?')}` at temperature "
        f"{metadata.get('reranker_temperature', '?')}, top_k={metadata.get('top_k', '?')}."
    )
    pkgs = metadata.get("packages", {})
    if pkgs:
        pkg_str = ", ".join(f"{k} {v}" for k, v in pkgs.items())
        lines.append(f"- **Packages:** {pkg_str}.")
    lines.append(
        "- **Isolation:** each approach runs in its own `InMemoryRunner`, one at a "
        "time, so latency and token counts carry no parallel-contention artifact."
    )
    lines.append(
        "- **Scope-leak probe (reproducible):** `examples/probe_scope_filter.py` "
        "replays the exact `search_entries` call the `KC Search` approach makes "
        "(`page_size=20`, `semantic_search=True`, the same `parent:(datasets/…)` "
        "query) and counts raw results vs. what survives the client-side scope "
        "filter, across a battery of query formulations and page sizes. It shows: "
        "the predicate *alone* returns only in-scope tables (enforceable); the "
        "combined question+predicate query leaks (a full page, mostly from "
        "unrelated datasets); exact `parent=`, the `fully_qualified_name` prefix, "
        "and `NOT` negation all leak identically; a wider page only adds pollution "
        "(in-scope pinned as `page_size` grows 20 → 100); and keyword mode "
        "(`semantic_search=False`) returns nothing for a natural-language "
        "question. The harness also records per-run `search_stats` "
        "(`raw_search_count`, `out_of_scope_dropped`) for every search-based cell."
    )
    lines.append("")
    return "\n".join(lines)


def readme_digest(scored: list[dict], approaches: list[str]) -> str:
    """Compact results digest injected into readme.md between the RESULTS markers.

    Leads with the finding (discovery vs rerank loss), then a one-line-per-
    approach recall table, then a pointer into the deep report. Kept short: the
    README summarizes, `examples/results.md` is the detail.
    """
    lines = [
        "_Auto-generated by `examples/build_results.py` — do not edit between the "
        "markers._",
        "",
        "**Recall leaks at discovery, not reranking.** The reranker almost never "
        "drops a must-have table that discovery surfaced; the search-based "
        "approaches are capped because semantic search leaves join-partner tables "
        "out of the candidate set entirely — for **two distinct reasons**: a "
        "*relevance gap* on disparate joins (the partner shares no term with the "
        "question) and a *scope leak* on related joins (the `parent:` filter, "
        "enforceable on its own, is relaxed when combined with a free-text "
        "question under semantic search, so unrelated-dataset tables fill the page "
        "budget and crowd the in-scope partner out).",
        "",
        "| Approach | Discovery recall | Final recall | Rerank loss |",
        "|---|---|---|---|",
    ]
    for a in approaches:
        disc = _mean([s["discovery_recall"] for s in scored if s["approach"] == a])
        final = _mean([s["final_recall"] for s in scored if s["approach"] == a])
        role = " (control)" if a in CONTROL_APPROACHES else ""
        lines.append(
            f"| {APPROACH_LABELS[a]}{role} | {_fmt_num(disc, 3)} | "
            f"{_fmt_num(final, 3)} | {_fmt_num(disc - final, 3)} |"
        )
    lines += [
        "",
        "**Why it matters at scale:** on a small corpus you route around search by "
        "feeding the whole corpus to the reranker — which is why enrichment tier "
        "does not move recall here. At thousands of tables that escape hatch "
        "closes: search *must* subset before reranking, so search recall becomes "
        "the pipeline's hard ceiling (the reranker can raise precision, never "
        "recall). The two mechanisms need different fixes, and one gates the "
        "other: **make the `parent:` scope predicate bind under semantic search** "
        "(a precondition — it is enforceable alone but relaxed once combined with "
        "a free-text question, and while that holds a wider page just admits more "
        "pollution) and add a **query-decomposition front-end that fans out into "
        "multiple targeted searches** for the relevance gap — plus a "
        "catalog-native option: join-aware search expansion via `frequent_joins`.",
        "",
        "Means across all questions × tiers × runs (medians saturate at 100% on "
        "this corpus). Worked example, scale discussion, full tables, plots, "
        "enrichment-response curves, per-category breakdown, cost/latency, and "
        "paired CIs: [`examples/results.md`](examples/results.md).",
    ]
    return "\n".join(lines)


def inject_readme_digest(digest: str) -> bool:
    """Replace the text between the RESULTS markers in readme.md with ``digest``.

    Returns True if the file was rewritten, False if the markers are absent (the
    digest is skipped rather than guessed at a location — the README owns where
    the section lives).
    """
    if not README_FILE.exists():
        return False
    text = README_FILE.read_text()
    if README_START not in text or README_END not in text:
        return False
    pre, rest = text.split(README_START, 1)
    _, post = rest.split(README_END, 1)
    new = f"{pre}{README_START}\n\n{digest}\n\n{README_END}{post}"
    if new == text:
        return False
    README_FILE.write_text(new)
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=str, default=str(RESULTS_FILE))
    parser.add_argument("--output", type=str, default=str(OUTPUT_MD))
    parser.add_argument("--no-plots", action="store_true", help="Skip PNG plots")
    args = parser.parse_args()

    results_path = Path(args.results)
    if not results_path.exists():
        raise SystemExit(f"No results at {results_path}. Run run_questions.py first.")

    with open(results_path) as f:
        doc = json.load(f)
    metadata = doc.get("metadata", {})
    cells = doc.get("cells", [])

    scored = []
    n_errors = 0
    empties: dict[str, int] = {}
    for cell in cells:
        s = score_cell(cell)
        if s is None:
            n_errors += 1
            continue
        if not cell.get("ranked_tables"):
            empties[cell["approach"]] = empties.get(cell["approach"], 0) + 1
        s.update({
            "question_id": cell["question_id"],
            "approach": cell["approach"],
            "tier": cell["tier"],
            "category": cell["category"],
        })
        scored.append(s)

    if not scored:
        raise SystemExit("No scorable cells found.")

    approaches = [a for a in APPROACH_LABELS if any(s["approach"] == a for s in scored)]
    tiers = sorted({s["tier"] for s in scored})
    categories = [c for c in CATEGORY_ORDER if any(s["category"] == c for s in scored)]

    plots: dict[str, str] = {}
    if not args.no_plots:
        plots = render_plots(scored, approaches, tiers, categories)

    def _img(name: str) -> str:
        """Markdown image for a rendered plot, or '' if plots were skipped."""
        return f"![{name}]({plots[name]})\n" if name in plots else ""

    parts = [
        "# NL2SQL retrieval benchmark — results",
        "",
        "Five table-discovery approaches for BigQuery NL2SQL, scored on a "
        "factorial experiment that isolates **catalog enrichment** as the "
        "independent variable. See `readme.md` for the challenge and approach "
        "spec cards, and `GROUND_TRUTH.md` for the grading rubric.",
        "",
        # Lead with the finding: where does recall actually leak?
        discovery_vs_rerank(scored, approaches),
        _img("discovery_vs_final"),
        discovery_miss_by_category(scored, approaches, categories),
        worked_example(cells),
        discussion_at_scale(scored, approaches),
        # Then the saturated overall + enrichment-response tables.
        headline_table(scored, approaches),
        tier_response_table(scored, approaches, tiers),
        _img("recall_vs_tier"),
        category_table(scored, approaches, categories),
        _img("ndcg_by_category"),
        cost_latency_table(scored, approaches),
        _img("latency_cost"),
        paired_comparison(scored, approaches),
        methodology_footer(metadata, len(scored), n_errors, empties),
    ]
    report = "\n".join(parts)

    Path(args.output).write_text(report)
    print(f"Wrote {args.output}")
    if plots:
        print(f"Wrote {len(plots)} plot(s) to {PLOTS_DIR}")

    digest = readme_digest(scored, approaches)
    if inject_readme_digest(digest):
        print(f"Injected results digest into {README_FILE}")


if __name__ == "__main__":
    main()
