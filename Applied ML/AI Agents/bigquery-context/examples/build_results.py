def cost_latency_table(scored: list[dict], approaches: list[str]) -> str:
    """Isolated latency (p50/p95) and reranker token cost per approach."""
    lines = ["## Cost & latency (isolated per-approach)", ""]
    lines += [
        "| Approach | Latency p50 (s) | Latency p95 (s) | Reranker tokens (median) | Reranker calls |",
        "|---|---|---|---|---|",
    ]
    for a in approaches:
        lat = [s["latency_s"] for s in scored if s["approach"] == a]
        tok = [s["reranker_total_tokens"] for s in scored if s["approach"] == a]
        calls = [s["reranker_calls"] for s in scored if s["approach"] == a]
        lines.append(
            f"| {APPROACH_LABELS[a]} | {_fmt_num(_pctl(lat, 50), 2)} | "
            f"{_fmt_num(_pctl(lat, 95), 2)} | {_fmt_num(_median(tok), 0)} | "
            f"{_fmt_num(_median(calls), 1)} |"
        )
    lines.append("")
    lines.append(
        "_Latency is wall-clock for one approach run in isolation (no parallel "
        "contention). Reranker tokens are exact from `usage_metadata`; they are "
        "the dominant model cost since discovery is otherwise deterministic._"
    )
    lines.append("")
    return "\n".join(lines)


def paired_comparison(scored: list[dict], approaches: list[str]) -> str:
    """Paired bootstrap CI of final-recall delta vs the bq_tools baseline."""
    baseline = "bq_tools"
    if baseline not in approaches:
        return ""
    lines = [f"## Paired comparison vs `{APPROACH_LABELS[baseline]}` (final recall)", ""]
    lines += ["| Approach | Mean Δ recall | 95% CI | Significant? |", "|---|---|---|---|"]

    base_cell = collapse_runs(
        [s for s in scored if s["approach"] == baseline], "final_recall"
    )
    # Key per-cell by (qid, tier) for pairing across approaches.
    base_by_qt = {(q, t): v for (q, a, t), v in base_cell.items()}

    for a in approaches:
        if a == baseline:
            continue
        a_cell = collapse_runs(
            [s for s in scored if s["approach"] == a], "final_recall"
        )
        deltas = []
        for (q, _a, t), v in a_cell.items():
            b = base_by_qt.get((q, t))
            if b is not None:
                deltas.append(v - b)
        med, lo, hi = bootstrap_paired_ci(deltas)
        sig = "yes" if (not math.isnan(lo) and (lo > 0 or hi < 0)) else "no"
        lines.append(
            f"| {APPROACH_LABELS[a]} | {_fmt_pct(med)} | "
            f"[{_fmt_pct(lo)}, {_fmt_pct(hi)}] | {sig} |"
        )
    lines.append("")
    lines.append(
        "_Paired over identical (question, tier) cells; CI from 2000-sample "
        "bootstrap. \"Significant\" = 95% CI excludes zero._"
    )
    lines.append("")
    return "\n".join(lines)


