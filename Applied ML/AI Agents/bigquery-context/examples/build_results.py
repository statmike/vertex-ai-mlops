"""Score the factorial benchmark, compute statistics, render plots + report.

Consumes ``examples/results/results.json`` (the raw approach-run cells written by
``run_questions.py``) and produces:

- ``examples/results.md`` — a scannable report: headline table → tier-response →
  per-category breakdown → cost/latency → methodology footer.
- ``examples/results/plots/*.png`` — recall-vs-tier curves, latency & cost bars,
  nDCG-by-category.

Scoring is graded (see ``GROUND_TRUTH.md``): ``must_have`` tables are the recall
numerator and carry nDCG gain 2; ``nice_to_have`` carry gain 1; ``distractor``
tables carry gain 0 and, when ranked, lower precision.

Run from the project root::

    uv run python examples/build_results.py            # write report + plots
    uv run python examples/build_results.py --no-plots # tables only

All metrics are aggregated as **median + IQR (p25–p75)** across the n replicate
runs of each (question, approach, tier) cell, then across questions. Paired
approach comparisons use a bootstrap CI over the per-question deltas (the
approaches see identical questions, so the comparison is paired).
"""

