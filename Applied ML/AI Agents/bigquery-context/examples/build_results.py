        "_Where the candidate set is complete (1.00) vs missing a must-have "
        "table. With the scoped query the search-based approaches reach ~1.00 on "
        "`single-table` and `multi-table-related` questions; the only sub-1.00 "
        "cells are in `multi-table-disparate`, driven by a single **relevance "
